test('fractional measured header height uses an integral occlusion ceiling and restores a real nonzero scroll origin', async t => {
  const f = await fixture(t, { mode: 'js-fixed' });
  await f.page.addStyleTag({ content: '.slot,.header{height:61.25px}' });
  await f.page.evaluate(() => scrollTo(0, 210)); await f.page.waitForTimeout(50);
  const receipt = await captureLayoutStableScreenshot(f.page, { path: f.filename, ownedTopHeader });
  assert.equal(receipt.passed, true, JSON.stringify(receipt.gaps));
  assert.equal(receipt.before.scrollY, 210); assert.equal(receipt.restored.scrollY, 210);
  assert.equal(receipt.ownedHeaderComposition?.headerHeightCSS, 61.25);
  assert.equal(receipt.ownedHeaderComposition?.overlapPixels, Math.ceil(61.25 * receipt.contentRaster.scale) + 1);
  assert(receipt.tiles.slice(1).every(tile => tile.cropTopPx >= Math.ceil(61.25 * receipt.contentRaster.scale)));
  assert.equal(receipt.ownedHeaderComposition?.coverage.gapFree, true);
});

test('actual offscreen and ancestor-suppressed fixed subtrees keep every row and preserve exact body pixel coverage on both desktops', async t => {
  for (const viewport of [{ width: 1920, height: 1080 }, { width: 1440, height: 1000 }]) {
    const f = await fixture(t, { ...viewport, extra: '<aside id="hidden-offcanvas" style="position:fixed;left:-400px;top:0;width:300px;height:200px;visibility:hidden"><div id="fixed-static-child" style="height:40px"></div></aside><div style="opacity:0"><aside id="suppressed-fixed-wrapper" style="position:fixed;left:200px;top:100px;width:100px;height:80px"><input id="suppressed-fixed-input" type="text"></aside></div>' });
    const original = await f.page.content(), receipt = await captureLayoutStableScreenshot(f.page, { path: f.filename, ownedTopHeader });
    assert.equal(receipt.passed, true, JSON.stringify(receipt.gaps)); assert.equal(await f.page.content(), original);
    assert.equal(receipt.ownedHeaderComposition?.layoutCoordinateFrames, 'header-relative-fixed-subtree-viewport-normal-document-v1');
    const frames = receipt.tiles.map(tile => tile.before.layoutCoordinateRows!);
    for (const id of ['hidden-offcanvas', 'fixed-static-child', 'suppressed-fixed-wrapper', 'suppressed-fixed-input']) {
      const rows = frames.map(frame => frame.find(row => row.id === id)!); assert(rows.every(Boolean));
      assert(rows.every(row => row.frame === 'viewport-fixed-subtree' && row.fixedRootIndex !== null));
      assert(rows.every(row => JSON.stringify(row.rawViewportBox) === JSON.stringify(rows[0].rawViewportBox)));
      assert(rows.every(row => JSON.stringify(row.normalizedBox) === JSON.stringify(rows[0].normalizedBox)));
      if (id.startsWith('suppressed-')) assert(rows.every(row => row.suppressed));
    }
    const { data, info } = await sharp(f.filename).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    for (let y = 0; y < info.height; y++) {
      const expected = y < 64 ? [200, 40, 50] : Math.floor((y - 64) / 16) % 2 ? [240, 180, 20] : [10, 120, 30];
      for (const x of [400, info.width - 20]) { const offset = (y * info.width + x) * info.channels; assert.deepEqual([...data.subarray(offset, offset + 3)], expected, `real row${y},x${x}`); }
    }
    assert.equal(receipt.ownedHeaderComposition?.coverage.gapFree, true); assert.equal(receipt.ownedHeaderComposition?.coverage.unoccluded, true);
  }
});

